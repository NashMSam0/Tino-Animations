export const DURATION=442;
export function clampTime(value:unknown):number {return typeof value==='number'&&Number.isFinite(value)?Math.max(0,Math.min(DURATION,value)):0;}
export function sceneAt(time:number):Scene {const t=clampTime(time);return SCENES.find(s=>t>=s.start&&t<s.end)??SCENES[SCENES.length-1];}
export function formatTime(value:number):string {const n=Math.floor(clampTime(value));return Math.floor(n/60)+':'+String(n%60).padStart(2,'0');}
export function parseProgress(raw:string|null):number {try {const v=JSON.parse(raw||'null');return v?.version===2?clampTime(v.time):0;}catch{return 0;}}

export function sceneProgress(time:number):number { const t=clampTime(time),s=sceneAt(t); return (t-s.start)/(s.end-s.start); }
